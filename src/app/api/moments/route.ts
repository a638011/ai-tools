function generate(data: { scene: string; tone: string; topic: string }): string {
  const { scene, tone, topic } = data
  const pool = templates[scene]?.[tone] || templates.travel.literary
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  const selected = shuffled.slice(0, 3)

  const sceneName: Record<string, string> = { travel:'旅行打卡', food:'美食分享', selfie:'自拍日常', work:'工作感悟', mood:'心情随笔', fitness:'健身打卡' }
  const toneName: Record<string, string> = { literary:'文艺范', funny:'搞笑逗比', cool:'高冷简约', warm:'温暖治愈', sassy:'凡尔赛' }

  let output = `💬 朋友圈文案推荐\n📍 场景：${sceneName[scene] || scene} | 🎭 风格：${toneName[tone] || tone}\n${topic ? `📝 主题：${topic}\n` : ''}\n${'━'.repeat(30)}\n`

  selected.forEach((text, i) => {
    output += `\n【方案${i + 1}】\n${text}\n`
  })

  output += `\n${'━'.repeat(30)}\n💡 可以根据实际情况微调用词，加上地点或@好友效果更佳`
  return output
}

export async function POST(req: NextRequest) {
  try {
    const data = await req.json()
    const content = generate(data)
    return NextResponse.json({ content })
  } catch {
    return NextResponse.json({ error: '生成失败，请重试' }, { status: 500 })
  }
}
